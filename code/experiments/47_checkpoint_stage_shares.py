#!/usr/bin/env python3
"""Per-family stage shares and b_outcome/b_intent ratios from the rescored checkpoints.

Why this exists. The earlier writeup claimed the outcome-bias shift was localized to SFT
and explicitly "not RLHF/DPO". On the post-digit-fix rescore (7-template basis, job
19030249) that no longer holds: SFT is sufficient in all three families, but its SHARE of
the total shift is recipe-dependent -- 85% in OLMo-2, 65% in Tulu-3, and only 27% in
Zephyr, whose shift is concentrated at DPO (73%). This script computes those shares from
the CSV so the writeups quote verifiable numbers rather than hand arithmetic.

It also retires the old "2.5-3.9x" b_outcome/b_intent figure, which came from the
pre-rescore single-template numbers. Base stages are excluded from the ratio because both
coefficients sit at ~0 there, making the quotient meaningless.

Outputs
  outputs/experiments/checkpoint_stage_shares.csv
  outputs/experiments/CHECKPOINT_STAGE_SHARES.md
"""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
EXP = os.path.join(ROOT, "outputs", "experiments")
SRC = os.path.join(EXP, "checkpoint_dissection.csv")
OUT_CSV = os.path.join(EXP, "checkpoint_stage_shares.csv")
OUT_MD = os.path.join(EXP, "CHECKPOINT_STAGE_SHARES.md")

# Both coefficients are ~0 at base, so b_outcome/b_intent is not interpretable there.
RATIO_MIN_DENOM = 0.01


def load():
    fams = {}
    for r in csv.DictReader(open(SRC)):
        fams.setdefault(r["family"], []).append(r)
    for rs in fams.values():
        rs.sort(key=lambda r: int(r["stage_idx"]))
    return fams


def main():
    fams = load()
    rows, ratios = [], []
    for fam, rs in fams.items():
        base = float(rs[0]["contrast"])
        total = float(rs[-1]["contrast"]) - base
        prev = base
        for r in rs:
            c = float(r["contrast"])
            b_int, b_out = float(r["b_intent"]), float(r["b_outcome"])
            is_base = r["stage"] == "base"
            step = 0.0 if is_base else c - prev
            ratio = (b_out / b_int) if abs(b_int) >= RATIO_MIN_DENOM else None
            if ratio is not None and not is_base:
                ratios.append((ratio, fam, r["stage"]))
            rows.append(dict(
                family=fam, stage=r["stage"], stage_idx=r["stage_idx"],
                model_id=r["model_id"], contrast=round(c, 4),
                step_from_prev="" if is_base else round(step, 4),
                share_of_total_pct="" if is_base else round(100 * step / total, 1),
                b_intent=round(b_int, 4), b_outcome=round(b_out, 4),
                outcome_over_intent="" if ratio is None else round(ratio, 2),
                rating_std=round(float(r["rating_std"]), 4),
                total_family_shift=round(total, 4),
            ))
            prev = c

    with open(OUT_CSV, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    print("wrote", OUT_CSV)

    lo, hi = min(ratios), max(ratios)
    md = [
        "# Checkpoint stage shares and outcome/intent ratios (rescored, 7-template basis)",
        "",
        "Generated by `code/experiments/47_checkpoint_stage_shares.py` from",
        "`checkpoint_dissection.csv` (job `19030249`, n_items=2086 = 298 stories x 7",
        "templates). Shares are each stage's step in contrast as a percentage of that",
        "family's total base -> final-stage shift.",
        "",
        "## Per-family stage shares",
        "",
        "| family | stage | contrast | step | share of family total | b_intent | b_outcome "
        "| b_out/b_int | rating_std |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        step = "-" if r["step_from_prev"] == "" else f"{r['step_from_prev']:+.4f}"
        share = "-" if r["share_of_total_pct"] == "" else f"{r['share_of_total_pct']:.1f}%"
        ratio = "n/a" if r["outcome_over_intent"] == "" else f"{r['outcome_over_intent']:.2f}"
        md.append(f"| {r['family']} | {r['stage']} | {r['contrast']:+.4f} | {step} | {share} "
                  f"| {r['b_intent']:+.4f} | {r['b_outcome']:+.4f} | {ratio} "
                  f"| {r['rating_std']:.4f} |")

    md += [
        "",
        "## What is recipe-dependent, and what is not",
        "",
        "**Sufficient everywhere.** SFT alone moves every family off a neutral base:",
    ]
    for fam, rs in fams.items():
        sft = next((r for r in rs if r["stage"] == "SFT"), None)
        if sft is None:
            continue
        base_c = float(rs[0]["contrast"])
        md.append(f"- {fam}: {base_c:+.4f} -> {float(sft['contrast']):+.4f} "
                  f"(drop of {abs(float(sft['contrast']) - base_c):.4f})")
    md += [
        "",
        "**Share is not.** The fraction of the total shift contributed by SFT versus",
        "preference optimization differs by pipeline:",
        "",
        "| family | SFT share | later-stage share | where the shift concentrates |",
        "|---|---:|---:|---|",
    ]
    for fam, rs in fams.items():
        srows = [r for r in rows if r["family"] == fam and r["stage"] != "base"]
        sft_share = next((r["share_of_total_pct"] for r in srows if r["stage"] == "SFT"), 0.0)
        later = sum(r["share_of_total_pct"] for r in srows if r["stage"] != "SFT")
        biggest = max(srows, key=lambda r: abs(r["share_of_total_pct"]))
        md.append(f"| {fam} | {sft_share:.1f}% | {later:.1f}% | {biggest['stage']} "
                  f"({biggest['share_of_total_pct']:.1f}%) |")

    md += [
        "",
        "## b_outcome / b_intent ratio",
        "",
        f"Across all non-base stages the ratio spans **{lo[0]:.1f}-{hi[0]:.1f}** "
        f"({lo[1]} {lo[2]} to {hi[1]} {hi[2]}). At each family's final stage:",
        "",
    ]
    for fam, rs in fams.items():
        r = rs[-1]
        md.append(f"- {fam} ({r['stage']}): {float(r['b_outcome']) / float(r['b_intent']):.1f}x")
    md += [
        "",
        "The point estimate is not the robust part; the direction is. `b_outcome` is several",
        "times larger than `b_intent` in every family at every post-base stage, but the",
        "multiplier itself varies by more than a factor of two across recipes, so it should",
        "be reported as a range and never as a single figure. The superseded "
        "\"2.5-3.9x\" value came from pre-rescore single-template fits.",
        "",
        "## Base engagement",
        "",
        "| family | base model | base rating_std | engaged? |",
        "|---|---|---:|---|",
    ]
    for fam, rs in fams.items():
        b = rs[0]
        std = float(b["rating_std"])
        md.append(f"| {fam} | {b['model_id']} | {std:.4f} | "
                  f"{'yes' if std > 0.02 else 'no (degenerate)'} |")
    md += [
        "",
        "All three bases are now engaged and near-zero on contrast, so the base -> tuned",
        "comparison is a like-for-like contrast between responsive models rather than a",
        "comparison against a non-responder. Tulu-3's base was previously degenerate",
        "(rating_std 0.018) and is now 0.0966.",
        "",
    ]
    open(OUT_MD, "w").write("\n".join(md))
    print("wrote", OUT_MD)
    print(f"  ratio range (non-base): {lo[0]:.2f} ({lo[1]} {lo[2]}) "
          f"to {hi[0]:.2f} ({hi[1]} {hi[2]})")


if __name__ == "__main__":
    main()
