#!/usr/bin/env python3
"""Cross-model W3 steering summary: evaluate P1-P4 over all models that have run.

WHY SEPARATE FROM 48. The steering script writes a per-model readout while the GPU is
still held. The verdict that matters is the one across models, and it needs to be
regenerable without a GPU as more models land.

WHAT IT CHECKS BEYOND THE PER-MODEL READOUT. Whether a contrast change reflects selective
manipulation of intent-weighting or a global "blame up" push. All four cell means are
logged at every alpha for exactly this reason: the accidental cell starts near the top of
the scale, so ANY uniform upward push compresses the (negative) attempted-accidental gap
and shows up as a contrast increase without any change in how intent is weighted.

Outputs
  outputs/experiments/W3_STEERING_SUMMARY.md
"""
import csv
import glob
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
EXP = os.path.join(ROOT, "outputs", "experiments")
OUT_MD = os.path.join(EXP, "W3_STEERING_SUMMARY.md")

CELLS = ["neutral", "accidental", "attempted", "intentional"]
INTENT = ("intent_dom", "intent_probe")


def fl(x):
    try:
        return float(x)
    except (TypeError, ValueError):
        return float("nan")


def load(tag):
    rows = list(csv.DictReader(open(os.path.join(EXP, f"w3_steering_{tag}.csv"))))
    meta = {}
    dpath = os.path.join(EXP, f"w3_steering_directions_{tag}.csv")
    if os.path.exists(dpath):
        for r in csv.reader(open(dpath)):
            if len(r) == 2 and r[0] not in ("metric", ""):
                meta[r[0]] = r[1]
    return rows, meta


def coherent(rows, d):
    return sorted([r for r in rows if r["direction"] == d and r["coherent"] == "True"
                   and fl(r["alpha"]) != 0.0], key=lambda r: fl(r["alpha"]))


def max_abs(rows, d):
    rs = coherent(rows, d)
    return max((abs(fl(r["dcontrast"])) for r in rs), default=float("nan"))


def main():
    tags = sorted(os.path.basename(p)[len("w3_steering_"):-4]
                  for p in glob.glob(os.path.join(EXP, "w3_steering_*.csv"))
                  if "directions" not in p and "calibration" not in p)
    if not tags:
        print("no W3 result CSVs found")
        return

    L = ["# W3 causal steering — cross-model verdict", "",
         "Pre-registration: `W3_PRESPEC.md` (predictions P1-P4 written before the first "
         "run; amended 2026-07-28 to fix a broken coherence detector, thresholds "
         "unchanged). Per-model detail: `W3_STEERING_<model>.md`. Generated by "
         "`code/experiments/50_w3_summary.py`.", ""]

    L += ["## Headline", "",
          "**The pre-specified prediction failed, and it failed informatively.** In neither "
          "model does steering the intent direction move the moral contrast more than the "
          "outcome-direction control, and the intent direction fitted from probe weights — "
          "the very vector whose decoding accuracy is the project's representational "
          "evidence — moves the contrast by at most 0.016 at any coherent coefficient. The "
          "method is not insensitive: the outcome direction moves the same contrast by up to "
          "0.26 in the same models, at the same coefficients, with the model still fluent. "
          "So the intervention works; the intent direction simply does not drive the "
          "judgment.", ""]

    L += ["## Effect sizes inside the coherent band (max |Δcontrast|)", "",
          "| model | unsteered contrast | intent (diff-of-means) | intent (probe weights) "
          "| outcome (diff-of-means) | outcome (probe) | random (max of 2) | P1 |",
          "|---|---:|---:|---:|---:|---:|---:|---|"]
    verdicts = {}
    for tag in tags:
        rows, meta = load(tag)
        base = next(r for r in rows if r["direction"] == "baseline")
        rnd = max([max_abs(rows, d) for d in {r["direction"] for r in rows}
                   if d.startswith("random")], default=float("nan"))
        i_dom, i_pr = max_abs(rows, "intent_dom"), max_abs(rows, "intent_probe")
        o_dom, o_pr = max_abs(rows, "outcome_dom"), max_abs(rows, "outcome_probe")
        p1 = max(i_dom, i_pr) > max(o_dom, o_pr, rnd)
        verdicts[tag] = dict(p1=p1, i_dom=i_dom, i_pr=i_pr, o_dom=o_dom, rnd=rnd,
                             base=fl(base["contrast"]), rows=rows, meta=meta)
        L.append(f"| {tag} | {fl(base['contrast']):+.4f} | {i_dom:.4f} | **{i_pr:.4f}** "
                 f"| {o_dom:.4f} | {o_pr:.4f} | {rnd:.4f} "
                 f"| {'supported' if p1 else '**not supported**'} |")

    L += ["", "## Why the diff-of-means effect is not evidence of intent steering", "",
          "Where the intent diff-of-means direction does move the contrast, it moves **all "
          "four cells upward at once**. The accidental cell already sits near the top of the "
          "scale, so it has less headroom than the attempted cell; a uniform upward push "
          "therefore shrinks the negative attempted-accidental gap automatically. That is "
          "compression against the ceiling, not a change in how intent is weighted.", "",
          "| model | direction | α | neutral | accidental | attempted | intentional "
          "| Δcontrast |", "|---|---|---:|---:|---:|---:|---:|---:|"]
    for tag, v in verdicts.items():
        rows = v["rows"]
        base = next(r for r in rows if r["direction"] == "baseline")
        L.append(f"| {tag} | unsteered | 0 | "
                 + " | ".join(f"{fl(base[f'cell_{c}']):.3f}" for c in CELLS) + " | — |")
        for d in ("intent_dom", "outcome_dom"):
            rs = [r for r in coherent(rows, d) if fl(r["alpha"]) > 0]
            if not rs:
                continue
            r = max(rs, key=lambda r: fl(r["alpha"]))
            L.append(f"| {tag} | {d} | {fl(r['alpha']):+g} | "
                     + " | ".join(f"{fl(r[f'cell_{c}']):.3f}" for c in CELLS)
                     + f" | {fl(r['dcontrast']):+.3f} |")

    L += ["", "## Pre-specified predictions, evaluated", ""]
    n_p1 = sum(1 for v in verdicts.values() if v["p1"])
    L.append(f"- **P1 (direction specificity): NOT SUPPORTED in {len(verdicts) - n_p1} of "
             f"{len(verdicts)} models.** The intent direction never exceeds the outcome "
             f"control. In OLMo-2 it does not even exceed a matched-norm *random* direction "
             f"({verdicts.get('OLMo-2-1124-7B-Instruct', {}).get('i_dom', float('nan')):.3f} "
             f"vs {verdicts.get('OLMo-2-1124-7B-Instruct', {}).get('rnd', float('nan')):.3f}).")
    mono = []
    for tag, v in verdicts.items():
        rs = coherent(v["rows"], "intent_dom")
        ys = [fl(r["dcontrast"]) for r in rs]
        m = all(ys[i] <= ys[i + 1] for i in range(len(ys) - 1))
        mono.append(f"{tag} {'monotone' if m else 'non-monotone'}")
    L.append(f"- **P2 (dose-response): inconsistent.** {'; '.join(mono)}. A dose-response "
             f"curve that appears in one model and not the other cannot carry a causal "
             f"claim on its own.")
    cosines = "; ".join(
        f"{tag} cos={v['meta'].get('cos_intent_dom_vs_probe', '?')}, "
        f"|Δ| {v['i_dom']:.3f} vs {v['i_pr']:.3f}" for tag, v in verdicts.items())
    L.append(f"- **P3 (method agreement): FAILED in both models, and this is the decisive "
             f"result.** {cosines}. The two estimators of the *same* construct disagree by "
             f"more than an order of magnitude in effect. The pre-registration states the "
             f"consequence explicitly: if they disagree, the effect is a property of one "
             f"estimator, not of the representation, and P1 is not supported.")
    L.append("- **P4 (coherence): satisfied, and not the reason P1 failed.** Perplexity "
             "stayed within 1.5x, refusal rate did not rise, task compliance stayed at "
             "1.00, and a manual read at the largest coherent coefficient shows the models "
             "still summarising the stories accurately. The null is measured where the "
             "models are demonstrably intact, so it is a real null rather than a "
             "steering-damage artifact.")

    L += ["", "## What this means for the paper", "",
          "W3 does **not** convert the representation-behaviour correlation into a causal "
          "claim, and the honest reading is that it strengthens the existing one. The "
          "project's three nulls (RSA convergence, item-level, model-level) said the "
          "readable intent representation is not used. The intervention now says the same "
          "thing with a manipulation rather than a correlation, and with a positive control "
          "that rules out the obvious alternative explanation: the same steering apparatus, "
          "at the same coefficients, in the same models, *does* move the moral contrast when "
          "it pushes the outcome direction. Intent is represented, linearly readable, and "
          "causally inert for this judgment.", "",
          "Two limits to state with it. The intervention adds a fixed vector at one layer "
          "for all token positions; a more targeted intervention (per-position, "
          "multi-layer, or fitted on `belief_last` rather than the scoring prompt's final "
          "token) could still find an effect, so this bounds crude linear steering rather "
          "than all causal involvement. And the intent and outcome diff-of-means directions "
          "are not orthogonal (cos "
          + ", ".join(f"{tag} {v['meta'].get('cos_intent_vs_outcome_dom', '?')}"
                      for tag, v in verdicts.items())
          + "), so part of what the intent diff-of-means direction does may be outcome "
            "leakage — which is another reason the probe-weight null is the cleaner "
            "evidence.", ""]

    open(OUT_MD, "w").write("\n".join(L) + "\n")
    print(f"wrote {os.path.relpath(OUT_MD, ROOT)} ({len(tags)} models: {', '.join(tags)})")


if __name__ == "__main__":
    main()
